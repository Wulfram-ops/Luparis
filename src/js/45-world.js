function wFind() {
  const q = $('w_q').value.trim().toLowerCase(),
    R = $('w_res');
  if (!q || !WS) {
    R.innerHTML = '';
    return;
  }
  const hits = [
    ...wStates.filter(x => x.n.toLowerCase().includes(q)).map(x => ({ k: 's', x })),
    ...wBurgs.filter(x => x.n.toLowerCase().includes(q)).map(x => ({ k: 'b', x })),
    ...wMarks.filter(x => x.n.toLowerCase().includes(q)).map(x => ({ k: 'm', x })),
  ].slice(0, 10);
  R.innerHTML =
    hits
      .map(
        (h, i) =>
          `<button type="button" data-wi="${i}"><span>${esc(h.x.n)}</span><small>${h.k === 's' ? esc(t('w_state')) : h.k === 'b' ? esc(h.x.s || '') : ''}</small></button>`,
      )
      .join('') || `<p class="small">${t('pl_none')}</p>`;
  R._hits = hits;
}
$('w_q').addEventListener('input', wFind);
