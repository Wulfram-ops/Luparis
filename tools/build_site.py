#!/usr/bin/env python3
"""Build app.js from src/js and stamp cache-busting versions into index.html.

The site's JavaScript is edited in src/js/ (one file per area, loaded in name order).
Every file after 00-prelude.js shares one block scope, exactly as the original single
script did, so function hoisting and load order are unchanged. The result is app.js.

Usage:
    python3 tools/build_site.py           # write app.js and update index.html
    python3 tools/build_site.py --check   # exit 1 if app.js or index.html is out of date
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "js"
APP = ROOT / "app.js"
INDEX = ROOT / "index.html"
CSS = ROOT / "css" / "luparis.css"
HEADER = "// Generated by tools/build_site.py from src/js/ — edit those files, not this one.\n"


def build_app() -> str:
    files = sorted(SRC.glob("*.js"))
    if not files or files[0].name != "00-prelude.js":
        sys.exit("src/js/00-prelude.js is missing")
    prelude = files[0].read_text(encoding="utf-8")
    body = "".join(f"// ---- {f.name}\n{f.read_text(encoding='utf-8')}" for f in files[1:])
    return f"{HEADER}{prelude}{{\n{body}}}\n"


def short_hash(data: str | bytes) -> str:
    raw = data.encode("utf-8") if isinstance(data, str) else data
    return hashlib.sha256(raw).hexdigest()[:10]


def stamp_index(html: str, app: str) -> str:
    css_v = short_hash(CSS.read_bytes())
    app_v = short_hash(app)
    html = re.sub(r'href="css/luparis\.css\?v=[^"]*"', f'href="css/luparis.css?v={css_v}"', html)
    html = re.sub(r'src="app\.js\?v=[^"]*"', f'src="app.js?v={app_v}"', html)
    return html


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only verify that the built files are up to date")
    args = parser.parse_args()

    app = build_app()
    index = stamp_index(INDEX.read_text(encoding="utf-8"), app)

    if args.check:
        stale = []
        if not APP.exists() or APP.read_text(encoding="utf-8") != app:
            stale.append("app.js")
        if INDEX.read_text(encoding="utf-8") != index:
            stale.append("index.html")
        if stale:
            print("Out of date: " + ", ".join(stale) + " — run python3 tools/build_site.py")
            return 1
        print("Build is up to date.")
        return 0

    APP.write_text(app, encoding="utf-8")
    INDEX.write_text(index, encoding="utf-8")
    print(f"app.js written ({len(app) // 1024} KB from {len(list(SRC.glob('*.js')))} files); index.html stamped.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
